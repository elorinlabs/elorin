export function typeFromMime(mime: string): DetectedFileType | null {
  const value = mime.split(";")[0].trim().toLowerCase();
  if (value === "text/plain" || value === "application/octet-stream")
    return null;
  if (value === "application/geo+json" || value === "text/json") return "json";
  return (
    (Object.entries(mimeMap).find(([, m]) => m === value)?.[0] as
      DetectedFileType | undefined) ??
    (
      {
        "application/x-zip-compressed": "zip",
        "application/javascript": "javascript",
        "text/xml": "xml",
      } as Record<string, DetectedFileType>
    )[value] ??
    null
  );
}
