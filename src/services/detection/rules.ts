export function extensionOf(name: string): string | null {
  if (name.startsWith(".") && !name.slice(1).includes(".")) return null;
  const i = name.lastIndexOf(".");
  return i > 0 && i < name.length - 1 ? name.slice(i + 1).toLowerCase() : null;
}
